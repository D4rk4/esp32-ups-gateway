"""Embed the local web page as deterministic gzip, without a filesystem partition."""
from pathlib import Path
import gzip

def embed(root):
    source = root / "web/index.html"
    target = root / "src/web_assets.hpp"
    if not source.exists():
        raise RuntimeError("web/index.html is missing")
    payload = gzip.compress(source.read_bytes(), compresslevel=9, mtime=0)
    rows = [", ".join(f"0x{x:02x}" for x in payload[i:i+20]) for i in range(0,len(payload),20)]
    text = "// Generated by tools/embed_web.py; edit web/index.html.\n#pragma once\n#include <Arduino.h>\n"
    text += "static const uint8_t WEB_GZIP[] PROGMEM = {\n" + ",\n".join(rows) + "\n};\n"
    text += f"static const size_t WEB_GZIP_SIZE = {len(payload)};\n"
    if not target.exists() or target.read_text() != text:
        target.write_text(text)

if "Import" in globals():
    Import("env")
    embed(Path(env.subst("$PROJECT_DIR")))
else:
    embed(Path(__file__).resolve().parent.parent)

